export const CHECKLIST_STATES = ['Предстои', 'Готов', 'Неприложим'];
const MAX_ITEMS = 60;

export const defaultChecklist = () => DEFAULT_CHECKLIST.map((item, i) => ({ id: `d${i + 1}`, ...item, state: 'Предстои', note: '' }));

export function validateChecklist(raw) {
  if (!Array.isArray(raw) || raw.length > MAX_ITEMS) return { error: `Списъкът може да има до ${MAX_ITEMS} документа.` };
  const items = [];
  for (const [i, row] of raw.entries()) {
    const label = clean(row?.label, 300);
    if (!label) return { error: `Документ ${i + 1}: въведете наименование.` };
    const state = CHECKLIST_STATES.includes(row.state) ? row.state : 'Предстои';
    items.push({
      id: clean(row.id, 20) || `u${i + 1}`,
      group: clean(row.group, 40) || 'Оферта',
      label,
      state,
      note: clean(row.note, 300),
    });
  }
  return { items };
}

